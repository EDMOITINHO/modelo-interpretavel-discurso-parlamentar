"""
Refine Dissertation semantic-shift outputs into interpretable final tables.

This script reads the outputs generated by 05_interpret_semantic_shift.py
and creates dissertation-facing tables focused on longitudinal institutional semantic
shift. It reduces noise from proper names and discursive markers without
silently deleting them from the audit trail.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd


DEFAULT_RESULTS_DIR = Path("resultados")

CORE_INSTITUTIONAL_TERMS = {
    "democracia", "democratico", "democratica", "constituicao", "constitucional",
    "judiciario", "stf", "supremo", "congresso", "camara", "senado",
    "parlamento", "governo", "presidente", "presidencia", "republica",
    "federacao", "estado", "direito", "justica", "impeachment", "eleicao",
    "eleicoes", "voto", "partido", "partidos", "oposicao", "base",
    "coalizao", "ministro", "ministros", "militar", "militares",
}

CONJUNCTURE_TERMS = {
    "impeachment", "coalizao", "governabilidade", "crise", "polarizacao",
    "oposicao", "base", "governista", "direita", "esquerda", "stf",
    "judiciario", "presidencia", "ministro", "ministros", "militar",
    "militares", "republicanos",
}

DISCURSIVE_MARKERS = {
    "convenhamos", "questiono", "imaginamos", "observe", "concretamente",
    "teoricamente", "explico", "adiantou", "acrescento", "permitimos",
    "impressiona", "dira", "argumentando", "percebam", "nitidamente",
    "observo", "questionamos", "perguntamos", "lembremos", "lembre",
}

KNOWN_NAMES = {
    "heleno", "rousseff", "dilma", "lula", "bolsonaro", "temer", "michel",
    "pacheco", "weber", "marques", "motta", "amin", "bacelar", "gaspar",
    "neri", "sabino", "avelino", "hamilton", "olavo", "diogo", "crivella",
    "ruy", "fausto", "leonidas", "trindade",
}

PAIR_CONTEXT = {
    "52-53": "pre-2011 baseline",
    "53-54": "pre-2011 to Dilma I",
    "54-55": "Dilma I to impeachment legislature",
    "55-56": "post-impeachment / Temer to Bolsonaro",
    "56-57": "Bolsonaro to Lula III",
}

TRANSITION_PAIRS = {"54-55", "55-56", "56-57"}
PAPER_FOCUS_PAIRS = {"54-55", "55-56"}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Create refined interpretable tables for Dissertation semantic shift."
    )
    parser.add_argument("--results-dir", type=Path, default=DEFAULT_RESULTS_DIR)
    parser.add_argument("--top-n", type=int, default=40)
    return parser.parse_args()


def read_csv(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Missing input file: {path}")
    return pd.read_csv(path)


def classify_term(term: str) -> str:
    if term in CORE_INSTITUTIONAL_TERMS:
        return "core_institutional"
    if term in CONJUNCTURE_TERMS:
        return "political_conjuncture"
    if term in DISCURSIVE_MARKERS:
        return "discursive_marker"
    if term in KNOWN_NAMES:
        return "proper_name_or_actor"
    return "other_lexical_candidate"


def add_pair_columns(adjacent: pd.DataFrame) -> pd.DataFrame:
    data = adjacent.copy()
    data["pair"] = data["source_leg"].astype(str) + "-" + data["target_leg"].astype(str)
    data["pair_context"] = data["pair"].map(PAIR_CONTEXT).fillna("")
    data["is_transition"] = data["pair"].isin(TRANSITION_PAIRS)
    data["is_paper_focus"] = data["pair"].isin(PAPER_FOCUS_PAIRS)
    return data


def pair_summary(adjacent: pd.DataFrame) -> pd.DataFrame:
    out = (
        adjacent.groupby("pair", as_index=False)
        .agg(
            source_leg=("source_leg", "first"),
            target_leg=("target_leg", "first"),
            n_terms=("term", "count"),
            mean_cosine_distance=("cosine_distance", "mean"),
            median_cosine_distance=("cosine_distance", "median"),
            p90_cosine_distance=("cosine_distance", lambda s: s.quantile(0.90)),
            p95_cosine_distance=("cosine_distance", lambda s: s.quantile(0.95)),
            max_cosine_distance=("cosine_distance", "max"),
        )
        .sort_values(["source_leg", "target_leg"])
    )
    out["pair_context"] = out["pair"].map(PAIR_CONTEXT).fillna("")
    out["is_transition"] = out["pair"].isin(TRANSITION_PAIRS)
    out["is_paper_focus"] = out["pair"].isin(PAPER_FOCUS_PAIRS)
    return out


def aggregate_terms(adjacent: pd.DataFrame, global_shift: pd.DataFrame) -> pd.DataFrame:
    adjacent = adjacent.copy()
    adjacent["term_class"] = adjacent["term"].map(classify_term)

    focus = adjacent[adjacent["term_class"].isin(["core_institutional", "political_conjuncture"])]

    strongest = (
        focus.sort_values("cosine_distance", ascending=False)
        .groupby("term", as_index=False)
        .first()[["term", "pair", "pair_context", "cosine_distance"]]
        .rename(columns={
            "pair": "strongest_pair",
            "pair_context": "strongest_pair_context",
            "cosine_distance": "strongest_adjacent_distance",
        })
    )

    grouped = (
        focus.groupby("term", as_index=False)
        .agg(
            term_class=("term_class", "first"),
            mean_adjacent_distance=("cosine_distance", "mean"),
            max_adjacent_distance=("cosine_distance", "max"),
            transition_mean_distance=("cosine_distance", lambda s: s[focus.loc[s.index, "is_transition"]].mean()),
            non_transition_mean_distance=("cosine_distance", lambda s: s[~focus.loc[s.index, "is_transition"]].mean()),
            paper_focus_mean_distance=("cosine_distance", lambda s: s[focus.loc[s.index, "is_paper_focus"]].mean()),
        )
    )

    global_cols = global_shift[["term", "cosine_distance", "euclidean_distance"]].rename(columns={
        "cosine_distance": "global_distance_52_57",
        "euclidean_distance": "global_euclidean_52_57",
    })

    result = grouped.merge(strongest, on="term", how="left").merge(global_cols, on="term", how="left")
    result["transition_minus_non_transition"] = result["transition_mean_distance"] - result["non_transition_mean_distance"]

    class_order = {"core_institutional": 0, "political_conjuncture": 1}
    result["_class_order"] = result["term_class"].map(class_order).fillna(9)
    return result.sort_values(
        ["_class_order", "paper_focus_mean_distance", "global_distance_52_57"],
        ascending=[True, False, False],
    ).drop(columns="_class_order")


def audit_noisy_top_terms(top_terms: pd.DataFrame) -> pd.DataFrame:
    data = top_terms.copy()
    data["term_class"] = data["term"].map(classify_term)
    data["use_in_main_table"] = data["term_class"].isin(["core_institutional", "political_conjuncture"])
    data["interpretation_note"] = np.where(
        data["term_class"].eq("discursive_marker"),
        "High drift, but mainly rhetorical/discursive; use as secondary evidence.",
        np.where(
            data["term_class"].eq("proper_name_or_actor"),
            "Actor/name; interpret as contextual political signal, not lexical concept.",
            "Candidate lexical item; inspect neighbors before using in text.",
        ),
    )
    return data


def interpretable_neighbors(neighbors: pd.DataFrame, final_terms: pd.DataFrame, top_n: int) -> pd.DataFrame:
    terms = final_terms.head(top_n)["term"].tolist()
    selected = neighbors[neighbors["term"].isin(terms)].copy()
    return selected.merge(
        final_terms[["term", "term_class", "strongest_pair", "global_distance_52_57"]],
        on="term",
        how="left",
    ).sort_values(["term_class", "term", "leg"])


def write_summary(path: Path, drift_pairs: pd.DataFrame, final_terms: pd.DataFrame) -> None:
    strongest_pair = drift_pairs.sort_values("mean_cosine_distance", ascending=False).iloc[0]
    lines = [
        "# Refined interpretable semantic-shift results",
        "",
        "## Longitudinal pattern",
        "",
        f"Mean drift increases from {drift_pairs.iloc[0]['mean_cosine_distance']:.4f} in {drift_pairs.iloc[0]['pair']} to {drift_pairs.iloc[-1]['mean_cosine_distance']:.4f} in {drift_pairs.iloc[-1]['pair']}.",
        f"The strongest adjacent pair is {strongest_pair['pair']} ({strongest_pair['pair_context']}), mean cosine distance {strongest_pair['mean_cosine_distance']:.4f}.",
        "",
        "## Main interpretable terms",
        "",
    ]
    for _, row in final_terms.head(15).iterrows():
        lines.append(
            f"- {row['term']}: {row['term_class']}; strongest pair {row['strongest_pair']}; "
            f"paper-focus mean {row['paper_focus_mean_distance']:.4f}; 52-57 distance {row['global_distance_52_57']:.4f}."
        )
    lines.extend([
        "",
        "## Interpretation rule",
        "",
        "The main table prioritizes institutional and political-conjunctural terms. Discursive markers and proper names are retained in the audit table but excluded from the dissertation-facing main ranking unless discussed as contextual evidence.",
        "",
    ])
    path.write_text("\n".join(lines), encoding="utf-8")


def main(args: argparse.Namespace) -> None:
    adjacent = add_pair_columns(read_csv(args.results_dir / "dissertacao_semantic_shift_adjacent.csv"))
    global_shift = read_csv(args.results_dir / "dissertacao_semantic_shift_52_57.csv")
    top_terms = read_csv(args.results_dir / "dissertacao_semantic_shift_top_terms.csv")
    neighbors = read_csv(args.results_dir / "dissertacao_semantic_shift_neighbors.csv")

    drift_pairs = pair_summary(adjacent)
    final_terms = aggregate_terms(adjacent, global_shift)
    noisy_audit = audit_noisy_top_terms(top_terms)
    final_neighbors = interpretable_neighbors(neighbors, final_terms, args.top_n)

    paths = {
        "drift_by_pair": args.results_dir / "dissertacao_final_drift_by_pair.csv",
        "main_terms": args.results_dir / "dissertacao_final_interpretable_terms.csv",
        "neighbors": args.results_dir / "dissertacao_final_interpretable_neighbors.csv",
        "audit": args.results_dir / "dissertacao_final_noisy_terms_audit.csv",
        "summary": args.results_dir / "dissertacao_final_interpretation_summary.md",
        "manifest": args.results_dir / "dissertacao_final_interpretable_manifest.json",
    }

    drift_pairs.to_csv(paths["drift_by_pair"], index=False, encoding="utf-8")
    final_terms.to_csv(paths["main_terms"], index=False, encoding="utf-8")
    final_neighbors.to_csv(paths["neighbors"], index=False, encoding="utf-8")
    noisy_audit.to_csv(paths["audit"], index=False, encoding="utf-8")
    write_summary(paths["summary"], drift_pairs, final_terms)

    manifest = {
        "purpose": "dissertation-facing interpretable semantic-shift tables",
        "main_table": str(paths["main_terms"]),
        "rule": "main ranking keeps institutional and political-conjunctural terms; noisy high-drift terms are audited separately",
        "outputs": {key: str(value) for key, value in paths.items()},
    }
    paths["manifest"].write_text(json.dumps(manifest, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"Saved final interpretable terms to: {paths['main_terms']}")
    print(f"Saved noisy-term audit to: {paths['audit']}")
    print(f"Saved final summary to: {paths['summary']}")


if __name__ == "__main__":
    main(parse_args())